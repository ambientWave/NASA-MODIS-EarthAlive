"""Product catalog generated from the AppEEARS product snapshot.

``products.json`` is generated by ``tools/build_catalog.py`` from
``data/appeears_products.json`` (a verbatim ``GET /api/product`` dump). Do not
hand-edit it: the drift tests fail when the curated overlay references a
product that is missing here.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from datetime import date, timedelta
from functools import lru_cache
from pathlib import Path

CATALOG_PATH = Path(__file__).with_name("products.json")


@dataclass(frozen=True)
class Product:
    name: str
    product_id: str
    version: str
    platform: str | None
    description: str | None
    raster_type: str | None
    resolution_raw: str | None
    resolution_m: float | None
    granularity_raw: str | None
    granularity: str
    step_days: float | None
    extent_start: date | None
    extent_end: date | None  # None means the provider still extends the series
    source: str | None
    provider_lag_days: int
    available: bool
    doi: str | None = None

    def extent_end_resolved(self, today: date | None = None) -> date:
        """Resolve the open-ended ``"Present"`` extent with the provider lag."""
        if self.extent_end is not None:
            return self.extent_end
        reference = today or date.today()
        return reference - timedelta(days=self.provider_lag_days)


def _parse_product(payload: dict) -> Product:
    start = payload.get("extent_start")
    end = payload.get("extent_end")
    return Product(
        name=payload["product"],
        product_id=payload.get("product_id") or payload["product"],
        version=str(payload.get("version") or ""),
        platform=payload.get("platform"),
        description=payload.get("description"),
        raster_type=payload.get("raster_type"),
        resolution_raw=payload.get("resolution_raw"),
        resolution_m=payload.get("resolution_m"),
        granularity_raw=payload.get("granularity_raw"),
        granularity=payload.get("granularity") or "irregular",
        step_days=payload.get("step_days"),
        extent_start=date.fromisoformat(start) if start else None,
        extent_end=date.fromisoformat(end) if end else None,
        source=payload.get("source"),
        provider_lag_days=int(payload.get("provider_lag_days") or 5),
        available=bool(payload.get("available", True)),
        doi=payload.get("doi"),
    )


@lru_cache(maxsize=1)
def load_catalog(path: str | Path | None = None) -> dict[str, Product]:
    target = Path(path) if path is not None else CATALOG_PATH
    payload = json.loads(target.read_text(encoding="utf-8"))
    return {name: _parse_product(item) for name, item in payload["products"].items()}


def get_product(name: str) -> Product:
    catalog = load_catalog()
    try:
        return catalog[name]
    except KeyError as exc:
        raise ValueError(f"Product '{name}' is not in the AppEEARS catalog.") from exc
